    private void habilitarBtn(){
        int n, k;
        
        switch (ops.getSelectedIndex()) {
            case 0 -> {
                n = Integer.parseInt(qtdElemt.getValue().toString());
                
                if (n == 0) {
                    exeBtn.setEnabled(false);
                } else {
                    exeBtn.setEnabled(true);
                }
            }
            
            case 3 -> {
                n = Integer.parseInt(qtdLins.getValue().toString());
                
                if (n == 0) {
                    exeBtn.setEnabled(false);
                } else {
                    exeBtn.setEnabled(true);
                }
            }
            
            default -> {
                n = Integer.parseInt(qtdElemt.getValue().toString());
                k = Integer.parseInt(qtdCombs.getValue().toString());
                
                if (n == 0 && k == 0) {
                    exeBtn.setEnabled(false);
                } else {
                    exeBtn.setEnabled(true);
                }
            }
        }
    }
    
    private void habilitarCampos(boolean elemt, boolean combs, boolean lins){
        Color cinza = new Color(153, 153, 153), preto = Color.BLACK;

        qtdElemt.setEnabled(elemt);
        qtdCombs.setEnabled(combs);
        qtdLins.setEnabled(lins);

        if (elemt) {
            lbElemt.setForeground(preto);
        } else {
            qtdElemt.setValue(0);
            lbElemt.setForeground(cinza);  
        }
        
        if (combs) {
            lbCombs.setForeground(preto);
        } else {
            qtdCombs.setValue(0);
            lbCombs.setForeground(cinza);  
        }
        
        if (lins) {
            lbLins.setForeground(preto);
        } else {
            qtdLins.setValue(0);
            lbLins.setForeground(cinza);  
        }
    }
    
    private long fatorial(long n) {
        return (n > 1) ? n * fatorial(n - 1) : 1;
    }
    
    private long binomial(long n, long k) {
        return (n >= k) ? fatorial(n) / (fatorial(n - k) * fatorial(k)) : 0;
    }
    
    @FunctionalInterface
    interface opers {
        void aplicar();
    }
    
    private void carregar(opers o) {
        Timer timer = new Timer(500, null);
        lbTerm4.setText("   carregando recursos");        
        
        timer.start();
                
        timer.addActionListener((ActionEvent e) -> {
            if (u % 4 == 0) {
                if (u < 5) {
                    lbTerm4.setText("   carregando recursos");
                } else {
                    lbTerm4.setText("   preparando resposta");
                }
            } else if (u == 11){
                o.aplicar();
                timer.stop();
            } else {
                lbTerm4.setText(lbTerm4.getText() + ".");
            }
            u++;
        }); 
    }
    
