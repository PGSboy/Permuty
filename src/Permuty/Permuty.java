    private void exeBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_exeBtnActionPerformed
        Color aviso = new Color(245,134, 37), reset = new Color(255, 255, 255);
        int n, k, op = ops.getSelectedIndex();
        u = 0;
        
        lbTerm2.setText("start"); 
        
        switch(op) {
            case 0 -> {
                n = Integer.parseInt(qtdElemt.getValue().toString());
                
                lbTerm4.setForeground(reset);
                lbTerm3.setText(String.format("perm(%d)", n));
                
                carregar(() -> {
                    lbTerm4.setText(String.format("Existem %d possibilidades", fatorial(n)));
                });
                
            }

            case 3 -> {
                n = Integer.parseInt(qtdLins.getValue().toString());
                
                lbTerm4.setForeground(reset);
                lbTerm3.setText(String.format("pascal(%d)", n));   
                
                carregar(() -> {
                    lbTerm4.setText("<html>");
                    for (int i = 0; i < n; i++) {
                        for (int j = 0; j < n; j++) {
                            int bnum = (int) binomial(i, j);

                            if (bnum != 0) {
                                lbTerm4.setText(String.format(lbTerm4.getText() + " %d", bnum));
                            }

                        }
                        lbTerm4.setText(lbTerm4.getText() + "<br>");
                    }
                    lbTerm4.setText(lbTerm4.getText() + "</html>");
                });              
            }
            
            default -> {
                n = Integer.parseInt(qtdElemt.getValue().toString());
                k = Integer.parseInt(qtdCombs.getValue().toString());
                
                lbTerm4.setForeground(aviso);
                
                if (n == 0) {
                    lbTerm3.setText(String.format("error(%d)", n));
                    lbTerm4.setText("Não é possível combinar 0 elementos");
                } else if (k == 0) {
                    lbTerm3.setText(String.format("error(%d)", k));
                    lbTerm4.setText("Combinações não poderá ser 0");
                } else {
                    lbTerm4.setForeground(reset);
                    
                    if(op == 1) {
                        lbTerm3.setText(String.format("arrj(%d, %d)", n, k));
                        
                        carregar(() -> {
                            lbTerm4.setText(String.format("Existem %d possibilidades", (n >= k) ? fatorial(n) / fatorial(n - k) : 0));
                        });
                    } else {
                        lbTerm3.setText(String.format("combs(%d, %d)", n, k));
                        
                        carregar(() -> {
                            lbTerm4.setText(String.format("Existem %d possibilidades", binomial(n, k)));
                        });
                    }   
                }
            }    
        }
    }//GEN-LAST:event_exeBtnActionPerformed

    private void opsItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_opsItemStateChanged
        if (evt.getStateChange() == ItemEvent.SELECTED) { //evitar duplicações
            switch(ops.getSelectedIndex()) {
                case 0 -> {
                    habilitarCampos(true, false, false);
                }
      
                case 3 -> {
                    habilitarCampos(false, false, true);
                }
                
                default -> {
                    habilitarCampos(true, true, false);
                }
            }    
        }
    }//GEN-LAST:event_opsItemStateChanged

